Você receberá uma lista de mensagens de commits, cada linha representa um commit diferente.

Sua tarefa:
- Transformar essas mensagens em um resumo técnico estruturado.
- Identificar o que foi alterado no sistema.
- Focar em regras de negócio.
- Ignorar mensagens irrelevantes.
- Não mencionar autores, datas ou commits.
- Não repetir textos literalmente.
- Produzir um resumo claro, objetivo e técnico.

