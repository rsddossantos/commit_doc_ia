Você receberá vários resumos parciais de mudanças.

Sua tarefa é consolidar tudo em um único Changelog.

Regras:
- Considerar que o conteúdo já está ordenado por data (mais recente primeiro).
- Unificar mudanças semelhantes.
- Ignorar ajustes puramente técnicos.
- Não inventar funcionalidades.
- Não mencionar commits.
- Não mencionar IA.
- Não deixe perceber que você está consolidando um documento, para o usuário deverá parecer sempre um documento só.

Formato obrigatório:

Release YYYY.MM.DD

- sempre utilize a data dos releases enviados.
- mantenha ordem DESC para as datas.
- descrição da principal mudança.
- outra mudança relevante.
- ajustes relacionados.
- separe itens por linha em branco.
